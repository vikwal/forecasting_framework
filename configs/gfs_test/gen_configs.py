"""Configs for the GFS benefit test (2026-10-27): ICON-D2 + ECMWF vs ICON-D2 + ECMWF + GFS.

Wind (parks_v1, 90 parks) and PV (parks_pv_v2_30min, 90 parks), each once for one randomly drawn park
(own model) and once centralized over all 90 parks. Train runs 2023-07-24 .. 2024-07-31, test runs
2024-08-01 .. 2025-07-31. Everything else is taken from the reference configs:
wind configs/parks_v1/config_parks_v1_cl.yaml, PV configs/pv_parks/config_pv_v1_cl_smoke.yaml.

    python configs/gfs_test/gen_configs.py
"""
import os
import random

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SITES = os.path.join(os.path.expanduser('~'), 'Work/pv_sim2real/docs/standorte_wetter_2026-10-26')
SEED = 20261027

WIND_REF = 'configs/parks_v1/config_parks_v1_cl.yaml'
PV_REF = 'configs/pv_parks/config_pv_v1_cl_smoke.yaml'

WIND_GFS = {
    'feats': ['gfs_wind_speed_h50', 'gfs_wind_speed_h80', 'gfs_wind_speed_h100'],
    'data': "  gfs_path: !ENV '${DATA_ROOT}/nwp_ready/gfs'\n",
}
PV_GFS = {
    'feats': ['gfs_ghi', 'gfs_tcc'],
    'data': "  gfs_solar_path: !ENV '${DATA_ROOT}/nwp_ready_pv/gfs/SOLAR'\n",
}


def _sub(txt: str, old: str, new: str) -> str:
    assert txt.count(old) == 1, f'expected exactly one {old!r}'
    return txt.replace(old, new)


def _files_block(ids: list[str]) -> str:
    rows = [', '.join(f"'{i}'" for i in ids[k:k + 5]) for k in range(0, len(ids), 5)]
    return '  files: [\n          ' + ',\n          '.join(rows) + ']\n'


def _replace_files(txt: str, ids: list[str]) -> str:
    start = txt.index('  files: [')
    end = txt.index(']\n', start) + 2
    return txt[:start] + _files_block(ids) + txt[end:]


def _add_gfs(txt: str, gfs: dict, models_old: str, feats_anchor: str) -> str:
    txt = _sub(txt, models_old, models_old.replace("]", ", 'gfs']"))
    txt = _sub(txt, feats_anchor, feats_anchor + ', ' + ', '.join(f"'{f}'" for f in gfs['feats']))
    txt = _sub(txt, '  freq:', gfs['data'] + '  freq:')
    return _sub(txt, '  random_seed:', '  next_n_grid_gfs: 1\n  random_seed:')


def wind(ids: list[str], gfs: bool, head: str) -> str:
    txt = open(os.path.join(ROOT, WIND_REF)).read()
    txt = txt[txt.index('data:'):]
    txt = _replace_files(txt, ids)
    txt = _sub(txt, "results_path: 'results/parks_v1'", "results_path: 'results/gfs_test'")
    if gfs:
        txt = _add_gfs(txt, WIND_GFS, "nwp_models: ['icon-d2', 'ecmwf']", "'ecmwf_wind_speed_h200'")
    return head + txt


def pv(ids: list[str], gfs: bool, head: str) -> str:
    txt = open(os.path.join(ROOT, PV_REF)).read()
    txt = txt[txt.index('data:'):]
    txt = _sub(txt, 'parks_pv_v1_30min', 'parks_pv_v2_30min')
    txt = _replace_files(txt, ids)
    for old, new in (("train_end: '2023-10-31 23:30'", "train_end: '2024-07-31 23:30'"),
                     ("test_start: '2023-11-01'", "test_start: '2024-08-01'"),
                     ("test_end: '2023-11-27'", "test_end: '2025-07-31'"),
                     ("data_cutoff: '2023-11-30'", "data_cutoff: '2025-08-03'"),
                     ('  epochs: 1\n', '  epochs: 100\n'),
                     ("results_path: 'results/pv_parks'", "results_path: 'results/gfs_test'")):
        txt = _sub(txt, old, new)
    if gfs:
        txt = _add_gfs(txt, PV_GFS, "nwp_models: ['icon-d2', 'ecmwf']", "'ecmwf_kc_gti', 'ecmwf_ghi'")
    return head + txt


def main():
    w_ids = pd.read_csv(os.path.join(SITES, 'wind_parks.csv'))['park_id'].tolist()
    p_ids = pd.read_csv(os.path.join(SITES, 'pv_parks.csv'))
    rng = random.Random(SEED)
    w_one = rng.choice(w_ids)
    # the single PV park needs a full training year: commissioned before the train window
    p_one = rng.choice(p_ids.loc[pd.to_datetime(p_ids['start_utc']) <= '2023-07-24', 'park_id'].tolist())
    p_ids = p_ids['park_id'].tolist()
    jobs = {
        'wind_one': (wind, [w_one]), 'wind_all': (wind, w_ids),
        'pv_one': (pv, [p_one]), 'pv_all': (pv, p_ids),
    }
    for name, (fn, ids) in jobs.items():
        for gfs in (False, True):
            arm = 'icon_ecmwf_gfs' if gfs else 'icon_ecmwf'
            head = (f'# GFS test 2026-10-27 ({name}, {arm}), generated by configs/gfs_test/gen_configs.py.\n'
                    f'# {len(ids)} park(s); train runs 2023-07-24 .. 2024-07-31, test 2024-08-01 .. 2025-07-31.\n')
            path = os.path.join(HERE, f'config_gfs_{name}_{arm}.yaml')
            with open(path, 'w') as f:
                f.write(fn(ids, gfs, head))
            print(path)
    print('wind park', w_one, '| pv park', p_one)


if __name__ == '__main__':
    main()
